#!/usr/bin/env node
/**
 * Regenerates the derived research files from data/research/**.json:
 *   - data/research/summaries.generated.json  (small; imported by the app)
 *   - data/research/index.generated.ts        (candidateId -> lazy JSON loader)
 *   - data/research/manifest.json             (status of EVERY registry candidate
 *                                              + data-quality audit)
 *
 * Research files themselves are never modified by this script.
 * Usage: node scripts/research/build-index.mjs
 */
import { register } from "node:module";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { validateResearch } from "./validate.mjs";

register("../alias-hooks.mjs", import.meta.url);

const ROOT = resolve(import.meta.dirname, "../..");
const DIR = join(ROOT, "data/research");
const SUMMARIES = join(DIR, "summaries.generated.json");
const today = new Date().toISOString().slice(0, 10);

// The registry imports the summaries file, so it must exist first.
if (!existsSync(SUMMARIES)) writeFileSync(SUMMARIES, "{}\n");

const { ALL_CANDIDATES, REGISTRY_ISSUES } = await import("../../lib/candidates/registry.ts");
const { CATEGORY_KEYS } = await import("../../lib/research/types.ts");
const byId = new Map(ALL_CANDIDATES.map((c) => [c.id, c]));

function expectedDir(c) {
  if (c.office === "president") return "presidential";
  if (c.office === "governor") return join("governorship", c.stateSlug);
  return join("senate", c.stateSlug, c.districtSlug);
}

function listJson(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return listJson(p);
    return f.endsWith(".json") && !/manifest|\.generated\./.test(f) ? [p] : [];
  });
}

const problems = [];
const summaries = {};
const loaders = [];
const researched = new Map();

for (const file of listJson(DIR).sort()) {
  const rel = relative(DIR, file).split(sep).join("/");
  let doc;
  try {
    doc = JSON.parse(readFileSync(file, "utf8"));
  } catch (e) {
    problems.push(`${rel}: invalid JSON — skipped (${e.message})`);
    continue;
  }
  const c = byId.get(doc.candidateId);
  if (!c) {
    problems.push(`${rel}: candidateId "${doc.candidateId}" is not in the registry — skipped`);
    continue;
  }
  const expected = `${expectedDir(c).split(sep).join("/")}/${c.id}.json`;
  if (rel !== expected) problems.push(`${rel}: expected location ${expected}`);
  const { errors } = validateResearch(doc);
  if (errors.length) {
    problems.push(`${rel}: ${errors.length} validation errors — excluded from the app until fixed`);
    researched.set(c.id, { doc, rel, invalid: true });
    continue;
  }

  const evidence = { strong: 0, moderate: 0, limited: 0, insufficient: 0 };
  for (const k of CATEGORY_KEYS) {
    const cat = doc.categories?.[k];
    evidence[cat ? cat.evidence : "insufficient"]++;
  }
  const offices = (doc.career ?? []).filter((e) =>
    ["political-office", "appointment"].includes(e.kind)
  );
  const highlights = offices.slice(-3).reverse().map((e) => `${e.title} (${e.period})`);
  const keywords = [
    doc.identity?.currentOffice,
    ...(doc.career ?? []).map((e) => e.title),
    ...(doc.identity?.professional ?? []),
  ].filter(Boolean);

  summaries[c.id] = {
    status: doc.status,
    verification: doc.verification,
    researchedAt: doc.researchedAt ?? null,
    sources: doc.sources?.length ?? 0,
    evidence,
    highlights,
    keywords: [...new Set(keywords)].slice(0, 20),
    hasExecutiveExperience: !!doc.identity?.hasExecutiveExperience,
  };
  loaders.push(`  ${JSON.stringify(c.id)}: () => import("./${rel}"),`);
  researched.set(c.id, { doc, rel, invalid: false });
}

writeFileSync(SUMMARIES, JSON.stringify(summaries, null, 2) + "\n");
writeFileSync(
  join(DIR, "index.generated.ts"),
  `// AUTO-GENERATED by scripts/research/build-index.mjs — do not edit.\n` +
    `// Maps candidate ids to lazily loaded research files (server-side only).\n\n` +
    `export const researchLoaders: Record<string, () => Promise<{ default: unknown }>> = {\n` +
    loaders.join("\n") +
    (loaders.length ? "\n" : "") +
    `};\n`
);

// ---------------- manifest ----------------
const imageExists = (p) => !!p && existsSync(join(ROOT, "public", p.replace(/^\//, "")));
const entries = [];
const totals = {};
const quality = { missingImageFile: 0, missingAge: 0, missingQualification: 0, unknownParty: [] };

for (const c of ALL_CANDIDATES) {
  const t = (totals[c.office] ??= { total: 0 });
  t.total++;
  if (!imageExists(c.image)) quality.missingImageFile++;
  if (c.office !== "president" && c.age == null) quality.missingAge++;
  if (c.office !== "president" && !c.qualification) quality.missingQualification++;
  if (c.partyName === c.party) quality.unknownParty.push(`${c.id} (${c.party})`);

  const r = researched.get(c.id);
  const status = r ? (r.invalid ? "REVIEW_REQUIRED" : r.doc.status) : "NOT_STARTED";
  t[status] = (t[status] ?? 0) + 1;
  const base = {
    id: c.id,
    name: c.name,
    office: c.office,
    state: c.state,
    district: c.district,
    status,
  };
  if (!r) {
    entries.push(base);
    continue;
  }
  const cats = r.doc.categories ?? {};
  entries.push({
    ...base,
    file: `data/research/${r.rel}`,
    verification: r.doc.verification,
    categoriesCompleted: CATEGORY_KEYS.filter((k) => cats[k] && cats[k].evidence !== "insufficient"),
    categoriesInsufficient: CATEGORY_KEYS.filter((k) => !cats[k] || cats[k].evidence === "insufficient"),
    sourcesCollected: r.doc.sources?.length ?? 0,
    dateResearched: r.doc.researchedAt ?? null,
    lastUpdated: r.doc.lastReviewed ?? r.doc.researchedAt ?? null,
    outstanding: r.doc.gaps ?? [],
  });
}

const manifest = {
  generatedAt: today,
  note:
    "Research status for every candidate in the registry. NOT_STARTED means no research file exists yet. " +
    "All automated research is AI_DRAFT until a human reviewer marks it REVIEWED or VERIFIED.",
  totals,
  dataQuality: {
    ...quality,
    unknownParty: quality.unknownParty,
    registryIssues: REGISTRY_ISSUES.length,
    registryIssueSample: REGISTRY_ISSUES.slice(0, 25),
  },
  problems,
  candidates: entries,
};
writeFileSync(join(DIR, "manifest.json"), JSON.stringify(manifest, null, 1) + "\n");

console.log(`Registry candidates: ${ALL_CANDIDATES.length}`);
for (const [office, t] of Object.entries(totals)) console.log(`  ${office}: ${JSON.stringify(t)}`);
console.log(`Research files indexed: ${loaders.length}`);
if (problems.length) {
  console.log("Problems:");
  problems.forEach((p) => console.log(`  - ${p}`));
}
